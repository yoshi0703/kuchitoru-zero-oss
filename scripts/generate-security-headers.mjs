import { createHash } from 'node:crypto'
import { readFile, rename, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url))
const repositoryRoot = path.resolve(scriptDirectory, '..')
const defaultTemplatePath = path.join(repositoryRoot, 'config/_headers.template')
const defaultOutputPath = path.join(repositoryRoot, 'public/_headers')
const defaultDocumentPath = path.join(repositoryRoot, 'index.html')
const placeholders = {
  appOrigin: '__APP_ORIGIN__',
  supabaseOrigin: '__SUPABASE_ORIGIN__',
  inlineScriptHashes: '__INLINE_SCRIPT_HASHES__',
}

function isLoopbackHostname(hostname) {
  return hostname === 'localhost' || hostname === '127.0.0.1' || hostname === '[::1]'
}

export function parseExactPublicOrigin(value, variableName) {
  if (!value || typeof value !== 'string') {
    throw new Error(`${variableName} is required`)
  }

  let url
  try {
    url = new URL(value)
  } catch {
    throw new Error(`${variableName} must be a valid absolute URL`)
  }

  if (url.username || url.password) {
    throw new Error(`${variableName} must not contain credentials`)
  }

  if (url.search || url.hash || url.pathname !== '/') {
    throw new Error(`${variableName} must be an origin without path, query, or fragment`)
  }

  if (url.protocol !== 'https:' && !(url.protocol === 'http:' && isLoopbackHostname(url.hostname))) {
    throw new Error(`${variableName} must use HTTPS outside loopback development`)
  }

  return url.origin
}

export function createInlineScriptSourceList(document) {
  const hashes = [...document.matchAll(/<script\b(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)]
    .map((match) => `'sha256-${createHash('sha256').update(match[1]).digest('base64')}'`)

  if (hashes.length === 0) {
    throw new Error('index.html must contain at least one inline script to hash')
  }

  return hashes.join(' ')
}

export function renderSecurityHeaders(template, environment, inlineScriptSourceList) {
  if (environment.VITE_E2E_TEST_MODE === '1') {
    throw new Error('VITE_E2E_TEST_MODE must never be enabled for a production build')
  }
  const appOrigin = parseExactPublicOrigin(
    environment.VITE_APP_ORIGIN,
    'VITE_APP_ORIGIN',
  )
  const supabaseOrigin = parseExactPublicOrigin(
    environment.VITE_SUPABASE_URL,
    'VITE_SUPABASE_URL',
  )

  for (const placeholder of Object.values(placeholders)) {
    if (!template.includes(placeholder)) {
      throw new Error(`Security header template is missing ${placeholder}`)
    }
  }

  const rendered = template
    .replaceAll(placeholders.appOrigin, appOrigin)
    .replaceAll(placeholders.supabaseOrigin, supabaseOrigin)
    .replaceAll(placeholders.inlineScriptHashes, inlineScriptSourceList)

  if (Object.values(placeholders).some((placeholder) => rendered.includes(placeholder))) {
    throw new Error('Security header template contains unresolved placeholders')
  }

  return `# Generated by scripts/generate-security-headers.mjs. Do not edit directly.\n${rendered.trim()}\n`
}

export async function generateSecurityHeaders({
  documentPath = defaultDocumentPath,
  environment = process.env,
  outputPath = defaultOutputPath,
  templatePath = defaultTemplatePath,
} = {}) {
  const [document, template] = await Promise.all([
    readFile(documentPath, 'utf8'),
    readFile(templatePath, 'utf8'),
  ])
  const rendered = renderSecurityHeaders(
    template,
    environment,
    createInlineScriptSourceList(document),
  )
  const temporaryPath = `${outputPath}.tmp-${process.pid}`

  await writeFile(temporaryPath, rendered, { encoding: 'utf8', mode: 0o644 })
  await rename(temporaryPath, outputPath)
  return outputPath
}

async function main() {
  const outputPath = await generateSecurityHeaders()
  console.log(`Generated ${path.relative(repositoryRoot, outputPath)}`)
}

const invokedPath = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : null
if (invokedPath === import.meta.url) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error))
    process.exitCode = 1
  })
}
